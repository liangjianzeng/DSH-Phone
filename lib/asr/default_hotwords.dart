/// 用户自定义分类的稳定 id（不在 [hotwordCategories] 内，词表由用户自填）。
const String kCustomHotwordCatId = 'custom';

/// 默认启用全部分类（开箱即用，含用户自定义分类）。
List<String> defaultHotwordCategoryIds() =>
    [for (final c in hotwordCategories) c.id, kCustomHotwordCatId];

/// 某分类的默认词表。
List<String> defaultCategoryWords(String id) =>
    hotwordCategories.firstWhere((c) => c.id == id).words;
